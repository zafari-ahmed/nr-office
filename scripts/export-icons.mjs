/**
 * Writes resources/icons/lucide.php: the inner SVG markup of every Lucide icon the app references,
 * so <x-icon> renders real SVG on the server (no icon pop-in after page load).
 * Run `npm run icons` after using a new icon name. Unknown names still fall back to client-side rendering.
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { icons } from 'lucide';

const pascal = (name) => name.split('-').map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join('');
const walk = (dir) => readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : [p];
});

// Any quoted kebab-case word in views and PHP that is a Lucide icon name.
const names = new Set();
for (const file of [...walk('resources/views'), ...walk('app'), ...walk('database/seeders')]) {
    for (const [, word] of readFileSync(file, 'utf8').matchAll(/["']([a-z][a-z0-9]*(?:-[a-z0-9]+)*)["']/g)) {
        if (icons[pascal(word)]) names.add(word);
    }
}

const esc = (v) => String(v).replace(/&/g, '&amp;').replace(/"/g, '&quot;');
const inner = (node) => node[2].map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).map(([k, v]) => `${k}="${esc(v)}"`).join(' ')}/>`).join('');

const rows = [...names].sort().map((n) => `    '${n}' => '${inner(icons[pascal(n)]).replace(/'/g, "\\'")}',`);
writeFileSync('resources/icons/lucide.php', `<?php\n\n// Generated by scripts/export-icons.mjs (npm run icons). Do not edit by hand.\n\nreturn [\n${rows.join('\n')}\n];\n`);
console.log(`Exported ${names.size} icons to resources/icons/lucide.php`);
